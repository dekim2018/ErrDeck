-- 10.1 의 나머지 테이블 14개. V1 의 projects, project_keys 와 합쳐 16개다.
-- 상태 값은 문자열과 CHECK 로 둔다. 열거형 타입은 값을 더할 때 마이그레이션이 번거롭다.

-- 콘솔 사용자. role 은 시스템을 만들 수 있는지만 가른다. 시스템 안의 권한은 system_members 에 있다(15.4).
CREATE TABLE users (
    id            BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    email         TEXT        NOT NULL UNIQUE,
    password_hash TEXT        NOT NULL,
    role          TEXT        NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- 프로젝트 묶음. 예: 팬파라이브(프로젝트 6개), CoPage
CREATE TABLE systems (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       TEXT        NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- V1 에서 외래 키 없이 만든 projects 가 가리키는 시스템이 이미 있으면 이름을 붙여 만들어 둔다.
INSERT INTO systems (id, name)
SELECT DISTINCT system_id, 'system-' || system_id FROM projects
ON CONFLICT DO NOTHING;
-- 직접 넣은 ID 다음부터 새 ID를 주도록 시퀀스를 맞춘다.
SELECT setval(pg_get_serial_sequence('systems', 'id'), COALESCE((SELECT max(id) FROM systems), 0) + 1, false);

ALTER TABLE projects ADD CONSTRAINT projects_system_id_fkey FOREIGN KEY (system_id) REFERENCES systems (id);
CREATE INDEX projects_system_id ON projects (system_id);

-- 권한은 시스템 단위로 준다(15.4).
CREATE TABLE system_members (
    system_id  BIGINT      NOT NULL REFERENCES systems (id),
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    role       TEXT        NOT NULL CHECK (role IN ('VIEWER', 'MEMBER', 'ADMIN', 'OWNER')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (system_id, user_id)
);
CREATE INDEX system_members_user_id ON system_members (user_id);

-- 소스맵 업로드용 프로젝트 토큰. 원문은 저장하지 않고 SHA-256 만 둔다(15.2).
CREATE TABLE api_tokens (
    id           BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id   BIGINT      NOT NULL REFERENCES projects (id),
    name         TEXT        NOT NULL,
    token_hash   TEXT        NOT NULL UNIQUE,
    scope        TEXT        NOT NULL DEFAULT 'releases' CHECK (scope IN ('releases')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    revoked_at   TIMESTAMPTZ
);
CREATE INDEX api_tokens_project_id ON api_tokens (project_id);

-- created_at 이 재발 판정의 순서 기준이다(6.6). 이름(커밋 해시)으로는 순서를 알 수 없다.
CREATE TABLE releases (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id BIGINT      NOT NULL REFERENCES projects (id),
    version    TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (project_id, version)
);

-- 소스맵 파일. 본문은 파일 저장 포트 뒤의 볼륨에 있고 여기에는 위치와 해시만 둔다(7.2).
CREATE TABLE release_artifacts (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    release_id BIGINT      NOT NULL REFERENCES releases (id),
    name       TEXT        NOT NULL,
    size       BIGINT      NOT NULL CHECK (size >= 0),
    sha256     TEXT        NOT NULL,
    path       TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (release_id, name)
);

-- 발생 횟수와 사용자 수는 ClickHouse 집계 테이블에 있고, 여기에는 바뀌는 상태와 시각만 둔다(6.5).
CREATE TABLE issues (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id          BIGINT      NOT NULL REFERENCES projects (id),
    status              TEXT        NOT NULL DEFAULT 'unresolved'
                                    CHECK (status IN ('unresolved', 'resolved', 'ignored', 'regressed')),
    title               TEXT        NOT NULL,
    -- 맨 위 앱 프레임. 목록에서 어디서 났는지 보여 준다.
    culprit             TEXT,
    first_seen          TIMESTAMPTZ NOT NULL,
    last_seen           TIMESTAMPTZ NOT NULL,
    last_release        TEXT,
    resolved_in_release TEXT,
    -- 무시 조건(6.6). 기한이나 횟수 중 먼저 닿는 쪽에서 미해결로 돌아간다.
    ignored_until       TIMESTAMPTZ,
    ignored_until_count BIGINT,
    assignee_id         BIGINT REFERENCES users (id),
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX issues_list ON issues (project_id, status, last_seen DESC);

-- 지문과 이슈의 대응(6.4). 유일 제약과 ON CONFLICT DO NOTHING 으로 같은 지문의 이슈가 두 번 생기지 않게 한다(6.5).
CREATE TABLE issue_fingerprints (
    project_id   BIGINT      NOT NULL REFERENCES projects (id),
    -- SHA-256 앞 16바이트의 16진수 32자(6장 끝)
    fingerprint  CHAR(32)    NOT NULL,
    issue_id     BIGINT      NOT NULL REFERENCES issues (id),
    rule_version INTEGER     NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (project_id, fingerprint)
);
CREATE INDEX issue_fingerprints_issue_id ON issue_fingerprints (issue_id);

CREATE TABLE issue_comments (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    issue_id   BIGINT      NOT NULL REFERENCES issues (id),
    user_id    BIGINT      NOT NULL REFERENCES users (id),
    body       TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX issue_comments_issue_id ON issue_comments (issue_id, created_at);

-- 세 번 처리에 실패한 원문(6.7). 7일 뒤 지우므로 시각 색인을 둔다.
CREATE TABLE quarantined_events (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id BIGINT      NOT NULL,
    raw        BYTEA       NOT NULL,
    reason     TEXT        NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX quarantined_events_created_at ON quarantined_events (created_at);
CREATE INDEX quarantined_events_project_id ON quarantined_events (project_id, created_at DESC);

-- 알림 규칙(16.1). window 는 예약어라 window_minutes 로 쓴다.
CREATE TABLE alert_rules (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id       BIGINT      NOT NULL REFERENCES projects (id),
    kind             TEXT        NOT NULL
                                 CHECK (kind IN ('new_issue', 'regression', 'frequency', 'latency', 'monitor_down', 'cert_expiry')),
    threshold        BIGINT,
    window_minutes   INTEGER,
    channel          TEXT        NOT NULL CHECK (channel IN ('slack', 'discord', 'email')),
    -- 웹훅 주소나 메일 주소
    target           TEXT        NOT NULL,
    cooldown_minutes INTEGER     NOT NULL DEFAULT 30 CHECK (cooldown_minutes > 0),
    enabled          BOOLEAN     NOT NULL DEFAULT true,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX alert_rules_project_id ON alert_rules (project_id);

-- 보낸 알림 기록이자 중복 발송 방지(16.2). 넣는 데 성공한 worker 만 보낸다.
CREATE TABLE notifications (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    rule_id    BIGINT      NOT NULL REFERENCES alert_rules (id),
    dedupe_key TEXT        NOT NULL,
    status     TEXT        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'sent', 'failed')),
    attempts   INTEGER     NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at    TIMESTAMPTZ,
    UNIQUE (rule_id, dedupe_key)
);

-- 업타임 모니터(9.1).
CREATE TABLE monitors (
    id                  BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    project_id          BIGINT      NOT NULL REFERENCES projects (id),
    url                 TEXT        NOT NULL,
    method              TEXT        NOT NULL DEFAULT 'GET' CHECK (method IN ('GET', 'HEAD')),
    interval_seconds    INTEGER     NOT NULL DEFAULT 60 CHECK (interval_seconds IN (30, 60, 300)),
    timeout_ms          INTEGER     NOT NULL DEFAULT 5000 CHECK (timeout_ms > 0),
    expected_status_min INTEGER     NOT NULL DEFAULT 200,
    expected_status_max INTEGER     NOT NULL DEFAULT 299,
    expected_body       TEXT,
    status              TEXT        NOT NULL DEFAULT 'unknown' CHECK (status IN ('unknown', 'up', 'down')),
    paused_until        TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (expected_status_min <= expected_status_max)
);
CREATE INDEX monitors_project_id ON monitors (project_id);

CREATE TABLE monitor_incidents (
    id         BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    monitor_id BIGINT      NOT NULL REFERENCES monitors (id),
    started_at TIMESTAMPTZ NOT NULL,
    ended_at   TIMESTAMPTZ,
    cause      TEXT
);
CREATE INDEX monitor_incidents_monitor_id ON monitor_incidents (monitor_id, started_at DESC);
-- 모니터마다 열린 장애 기록은 하나뿐이다.
CREATE UNIQUE INDEX monitor_incidents_open ON monitor_incidents (monitor_id) WHERE ended_at IS NULL;
